def test_aes_sbox_differential_probability():
    dp, _, _ = differential_probability(AES_SBOX, 8)
    assert dp == pytest.approx(4 / 256)


def test_aes_sbox_linear_probability():
    lp, _, _ = linear_probability(AES_SBOX, 8)
    assert lp == pytest.approx((16 / 128) ** 2)


def test_identity_is_maximally_differential_and_linear():
    f = np.arange(256, dtype=np.uint16)
    dp, _, _ = differential_probability(f, 8)
    lp, _, _ = linear_probability(f, 8)
    assert dp == pytest.approx(1.0)
    assert lp == pytest.approx(1.0)


def test_constant_map():
    """Documenta la ambiguedad de `max_{a,b != 0}` en la ecuacion (9).

    Con a != 0 el mapa constante no admite aproximacion lineal (PAL = 0). Si se
    admite a = 0, la aproximacion degenera en "f(x).b = 0", que para una f
    constante se cumple siempre y da PAL = 1 sin que haya linealidad alguna.
    Por eso el valor por defecto exige a != 0.
    """
    f = np.full(256, 0x5a, dtype=np.uint16)
    dp, _, _ = differential_probability(f, 8)
    assert dp == pytest.approx(1.0)   # la diferencia de salida es siempre 0
    assert linear_probability(f, 8)[0] == pytest.approx(0.0)
    lax = linear_probability(f, 8, require_nonzero_input_mask=False)
    assert lax[0] == pytest.approx(1.0)
    assert lax[1] == 0


def test_bit_permutation_is_linear():
    """Permutar bits es afin: DP = LP = 1."""
    x = np.arange(256, dtype=np.uint16)
    f = ((x << 3) | (x >> 5)) & 0xFF
    dp, _, _ = differential_probability(f.astype(np.uint16), 8)
    lp, _, _ = linear_probability(f.astype(np.uint16), 8)
    assert dp == pytest.approx(1.0)
    assert lp == pytest.approx(1.0)


def test_dp_argmax_is_consistent():
    """El dx, dy devueltos deben reproducir el conteo maximo."""
    dp, dx, dy = differential_probability(AES_SBOX, 8)
    x = np.arange(256, dtype=np.uint16)
    count = int(np.sum((AES_SBOX[x] ^ AES_SBOX[x ^ dx]) == dy))
    assert count / 256 == pytest.approx(dp)
    assert dx != 0


def test_lp_argmax_is_consistent():
    lp, a, b = linear_probability(AES_SBOX, 8)
    x = np.arange(256, dtype=np.uint16)

    def parity(v):
        return np.array([bin(int(t)).count("1") & 1 for t in v])

    matches = int(np.sum(parity(x & a) == parity(AES_SBOX[x] & b)))
    assert ((matches - 128) / 128) ** 2 == pytest.approx(lp)
    assert b != 0
